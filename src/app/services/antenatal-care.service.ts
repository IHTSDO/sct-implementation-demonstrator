import { HttpClient } from '@angular/common/http';
import { Injectable } from '@angular/core';
import { firstValueFrom } from 'rxjs';
import type { Condition, Encounter, EpisodeOfCare, FhirObservation, Patient, QuestionnaireResponse } from '../model';
import { PatientService } from './patient.service';

const ASSETS_BASE = 'assets/questionnaires/who-anc';

const SNOMED = 'http://snomed.info/sct';
const ANC_CARE_CODES = 'http://smart.who.int/anc/CodeSystem/anc-care-codes';
const ANC_CUSTOM_CODES = 'http://smart.who.int/anc/CodeSystem/anc-custom-codes';
const ANC_CASE_CODE = 'ANC.Case';
const LMP_SNOMED_CODE = '21840007';

// The WHO profile and extension definition use `contactnumber`; the 0.3.0 CQL reads
// `contactNumber`. Both are written until the decision logic moves to the conformant one.
const CONTACT_NUMBER_EXTENSION_URLS = [
  'http://smart.who.int/anc/StructureDefinition/contactnumber',
  'http://smart.who.int/anc/StructureDefinition/contactNumber'
];

// ANC data dictionary codes of the items the module pre-fills.
const ANC_LMP_CODE = 'ANC.B6.DE14';
const ANC_GESTATIONAL_AGE_CODE = 'ANC.B6.DE17';
const ANC_EDD_CODE = 'ANC.B6.DE22';

const DAY_MS = 24 * 60 * 60 * 1000;
const PREGNANCY_LENGTH_DAYS = 280;

export type AncQuestionnaireRole = 'contact' | 'referral' | 'end-of-pregnancy';

export interface AncQuestionnaireEntry {
  id: string;
  role: AncQuestionnaireRole;
  firstContactOnly?: boolean;
  file: string;
  url: string;
  title: string;
  items: number;
}

export interface AncManifest {
  source: { package: string; version: string; buildDate: string; url: string; license: string };
  questionnaires: AncQuestionnaireEntry[];
}

/**
 * Antenatal care record: one EpisodeOfCare per pregnancy and one Encounter per contact,
 * following the WHO SMART ANC implementation guide. The forms are the SDC-adapted WHO
 * Questionnaires generated by `npm run sync:who-anc`.
 */
@Injectable({ providedIn: 'root' })
export class AntenatalCareService {
  private manifestPromise: Promise<AncManifest> | null = null;
  private questionnairePromises = new Map<string, Promise<any>>();

  constructor(
    private http: HttpClient,
    private patientService: PatientService
  ) {}

  // ─── Questionnaires ─────────────────────────────────────────────────────────

  loadManifest(): Promise<AncManifest> {
    if (!this.manifestPromise) {
      this.manifestPromise = firstValueFrom(this.http.get<AncManifest>(`${ASSETS_BASE}/index.json`));
    }
    return this.manifestPromise;
  }

  loadQuestionnaire(entry: AncQuestionnaireEntry): Promise<any> {
    if (!this.questionnairePromises.has(entry.id)) {
      this.questionnairePromises.set(entry.id, firstValueFrom(this.http.get(`${ASSETS_BASE}/${entry.file}`)));
    }
    return this.questionnairePromises.get(entry.id)!;
  }

  /** Forms of one contact, in WHO workflow order. "Confirm pregnancy" is first-contact only. */
  getContactForms(manifest: AncManifest, contactNumber: number): AncQuestionnaireEntry[] {
    return manifest.questionnaires.filter(
      (entry) => entry.role === 'contact' && (!entry.firstContactOnly || contactNumber === 1)
    );
  }

  // ─── Pregnancy (EpisodeOfCare) ──────────────────────────────────────────────

  async loadPregnancies(patientId: string): Promise<EpisodeOfCare[]> {
    const episodes = await this.patientService.loadPatientEpisodesOfCare(patientId);
    return episodes
      .filter((episode) => this.isAntenatalCase(episode))
      .sort((a, b) => (b.period?.start || '').localeCompare(a.period?.start || ''));
  }

  async startPregnancy(patient: Patient, lastMenstrualPeriod: Date): Promise<EpisodeOfCare> {
    const now = new Date().toISOString();
    const subject = { reference: `Patient/${patient.id}`, display: this.patientDisplay(patient) };

    const condition = await this.patientService.addPatientConditionAllowDuplicatesEnriched(patient.id, {
      resourceType: 'Condition',
      id: this.newId('condition'),
      clinicalStatus: {
        coding: [{ system: 'http://terminology.hl7.org/CodeSystem/condition-clinical', code: 'active', display: 'Active' }],
        text: 'Active'
      },
      verificationStatus: {
        coding: [{ system: 'http://terminology.hl7.org/CodeSystem/condition-ver-status', code: 'confirmed', display: 'Confirmed' }],
        text: 'Confirmed'
      },
      category: [{
        coding: [{ system: 'http://terminology.hl7.org/CodeSystem/condition-category', code: 'problem-list-item', display: 'Problem List Item' }],
        text: 'Problem List Item'
      }],
      code: {
        coding: [
          { system: SNOMED, code: '77386006', display: 'Pregnancy' },
          { system: ANC_CARE_CODES, code: 'ANC.Pregnancy', display: 'Pregnancy' }
        ],
        text: 'Pregnancy'
      },
      subject,
      onsetDateTime: lastMenstrualPeriod.toISOString(),
      recordedDate: now
    } as Condition);

    const episode = await this.patientService.createPatientEpisodeOfCare(patient.id, {
      resourceType: 'EpisodeOfCare',
      id: this.newId('episode-of-care'),
      status: 'active',
      type: [{
        coding: [{ system: ANC_CARE_CODES, code: ANC_CASE_CODE, display: 'Antenatal care case' }],
        text: 'Antenatal care case'
      }],
      diagnosis: [{
        condition: { reference: `Condition/${condition.id}`, display: 'Pregnancy' },
        role: { coding: [{ system: 'http://terminology.hl7.org/CodeSystem/diagnosis-role', code: 'CC', display: 'Chief complaint' }] }
      }],
      patient: subject,
      period: { start: now }
    });

    // The last menstrual period belongs to the pregnancy, not to a contact: it is linked
    // to the episode through `focus` and has no encounter.
    this.patientService.addPatientObservation(patient.id, {
      resourceType: 'Observation',
      id: this.newId('observation'),
      status: 'final',
      code: {
        coding: [
          { system: SNOMED, code: LMP_SNOMED_CODE, display: 'Date of last menstrual period' },
          { system: ANC_CUSTOM_CODES, code: ANC_LMP_CODE, display: 'Last menstrual period (LMP) date' }
        ],
        text: 'Date of last menstrual period'
      },
      subject,
      focus: [{ reference: `EpisodeOfCare/${episode.id}` }],
      effectiveDateTime: now,
      issued: now,
      valueDateTime: this.toDateOnly(lastMenstrualPeriod)
    });

    return episode;
  }

  async endPregnancy(patientId: string, episode: EpisodeOfCare): Promise<EpisodeOfCare> {
    return this.patientService.updatePatientEpisodeOfCare(patientId, episode.id, {
      ...episode,
      status: 'finished',
      period: { ...episode.period, end: new Date().toISOString() }
    });
  }

  /** Last menstrual period of the pregnancy as `YYYY-MM-DD`, or null when not recorded. */
  getLastMenstrualPeriod(patientId: string, episodeId: string): string | null {
    const reference = `EpisodeOfCare/${episodeId}`;
    const observation = this.patientService.getPatientObservations(patientId).find((candidate: FhirObservation) =>
      candidate.focus?.some((focus) => focus.reference === reference) &&
      candidate.code?.coding?.some((coding) => coding.system === SNOMED && coding.code === LMP_SNOMED_CODE)
    );
    return observation?.valueDateTime?.slice(0, 10) || null;
  }

  /** Completed weeks of gestation at `at`, counted from the last menstrual period. */
  gestationalAgeWeeks(lastMenstrualPeriod: string | null, at: Date = new Date()): number | null {
    const days = this.gestationalAgeDays(lastMenstrualPeriod, at);
    return days === null ? null : Math.floor(days / 7);
  }

  gestationalAgeDays(lastMenstrualPeriod: string | null, at: Date = new Date()): number | null {
    if (!lastMenstrualPeriod) {
      return null;
    }
    const days = Math.floor((this.startOfDay(at).getTime() - this.parseDateOnly(lastMenstrualPeriod).getTime()) / DAY_MS);
    return days >= 0 ? days : null;
  }

  /** Estimated date of delivery (`YYYY-MM-DD`): last menstrual period plus 280 days. */
  estimatedDateOfDelivery(lastMenstrualPeriod: string | null): string | null {
    if (!lastMenstrualPeriod) {
      return null;
    }
    const date = this.parseDateOnly(lastMenstrualPeriod);
    date.setDate(date.getDate() + PREGNANCY_LENGTH_DAYS);
    return this.toDateOnly(date);
  }

  // ─── Contacts (Encounter) ───────────────────────────────────────────────────

  getContacts(patientId: string, episodeId: string): Encounter[] {
    const reference = `EpisodeOfCare/${episodeId}`;
    return this.patientService.getPatientEncounters(patientId)
      .filter((encounter) => encounter.episodeOfCare?.some((episode) => episode.reference === reference))
      .sort((a, b) => this.getContactNumber(a) - this.getContactNumber(b));
  }

  getContactNumber(encounter: Encounter): number {
    const extension = encounter.extension?.find((candidate) => CONTACT_NUMBER_EXTENSION_URLS.includes(candidate.url));
    return extension?.valueInteger ?? 0;
  }

  async startContact(patient: Patient, episode: EpisodeOfCare): Promise<Encounter> {
    const previousContacts = this.getContacts(patient.id, episode.id);
    const contactNumber = previousContacts.reduce((max, contact) => Math.max(max, this.getContactNumber(contact)), 0) + 1;

    return this.patientService.createPatientEncounter(patient.id, {
      resourceType: 'Encounter',
      id: this.newId('encounter'),
      extension: this.contactNumberExtensions(contactNumber),
      status: 'in-progress',
      class: { system: 'http://terminology.hl7.org/CodeSystem/v3-ActCode', code: 'AMB', display: 'ambulatory' },
      type: [{
        coding: [{ system: SNOMED, code: '424525001', display: 'Antenatal care' }],
        text: 'Antenatal care contact'
      }],
      subject: { reference: `Patient/${patient.id}`, display: this.patientDisplay(patient) },
      episodeOfCare: [{ reference: `EpisodeOfCare/${episode.id}` }],
      period: { start: new Date().toISOString() }
    });
  }

  async closeContact(patientId: string, encounter: Encounter): Promise<Encounter> {
    return this.patientService.updatePatientEncounter(patientId, encounter.id, {
      ...encounter,
      status: 'finished',
      period: { ...encounter.period, end: new Date().toISOString() }
    });
  }

  // ─── Forms of a contact (QuestionnaireResponse) ─────────────────────────────

  getContactResponses(patientId: string, encounterId: string): QuestionnaireResponse[] {
    const reference = `Encounter/${encounterId}`;
    return this.patientService.getPatientQuestionnaireResponses(patientId)
      .filter((response) => response.encounter?.reference === reference);
  }

  /**
   * Saves a form. Within a contact it replaces the previous answers of the same form;
   * without one (the end-of-pregnancy form) it is stored at patient level.
   */
  saveResponse(patient: Patient, questionnaire: any, fhirResponse: any, encounter?: Encounter | null): QuestionnaireResponse {
    const existing = encounter
      ? this.getContactResponses(patient.id, encounter.id).find((response) => response.questionnaire === questionnaire.url)
      : undefined;

    const response: QuestionnaireResponse = {
      resourceType: 'QuestionnaireResponse',
      id: existing?.id || this.newId('qr'),
      questionnaire: questionnaire.url,
      status: existing ? 'amended' : 'completed',
      subject: { reference: `Patient/${patient.id}`, display: this.patientDisplay(patient) },
      ...(encounter ? { encounter: { reference: `Encounter/${encounter.id}` } } : {}),
      authored: new Date().toISOString(),
      item: fhirResponse?.item || [],
      questionnaireId: questionnaire.id,
      questionnaireName: questionnaire.title,
      questionnaireTitle: questionnaire.title
    };

    if (existing) {
      this.patientService.updatePatientQuestionnaireResponse(patient.id, existing.id, response);
    } else {
      this.patientService.addPatientQuestionnaireResponse(patient.id, response);
    }
    return response;
  }

  /**
   * Answers the module already knows for a form that has not been filled in this contact:
   * the registration data of the contact and the pregnancy dating derived from the last
   * menstrual period. The clinician can change any of them before saving.
   */
  buildInitialResponse(
    questionnaire: any,
    patient: Patient,
    encounter: Encounter,
    lastMenstrualPeriod: string | null
  ): any | null {
    const contactDate = new Date(encounter.period.start);
    const items: any[] = [];

    for (const item of questionnaire?.item || []) {
      const answer = this.knownAnswer(item, patient, encounter, contactDate, lastMenstrualPeriod);
      if (answer) {
        items.push({ linkId: item.linkId, text: item.text, answer: [answer] });
      }
    }

    if (!items.length) {
      return null;
    }
    return { resourceType: 'QuestionnaireResponse', status: 'in-progress', questionnaire: questionnaire.url, item: items };
  }

  /**
   * Applies the registration answers that belong to the Encounter (contact date and
   * contact number) and resolves with the updated contact. Other forms leave it untouched.
   */
  async applyResponseToContact(patientId: string, encounter: Encounter, questionnaire: any, fhirResponse: any): Promise<Encounter> {
    let updated: Encounter | null = null;

    for (const item of questionnaire?.item || []) {
      const answer = (fhirResponse?.item || []).find((responseItem: any) => responseItem.linkId === item.linkId)?.answer?.[0];
      if (!answer) {
        continue;
      }
      const definition: string = item.definition || '';
      if (definition.endsWith('#Encounter.period.start')) {
        const start = answer.valueDateTime || answer.valueDate;
        if (start && start !== encounter.period.start) {
          updated = { ...(updated || encounter), period: { ...encounter.period, start } };
        }
      } else if (definition.endsWith('#Encounter.contactNumber') && Number.isInteger(answer.valueInteger)) {
        if (answer.valueInteger !== this.getContactNumber(encounter)) {
          const otherExtensions = (encounter.extension || []).filter((extension) => !CONTACT_NUMBER_EXTENSION_URLS.includes(extension.url));
          updated = { ...(updated || encounter), extension: [...otherExtensions, ...this.contactNumberExtensions(answer.valueInteger)] };
        }
      }
    }

    return updated ? this.patientService.updatePatientEncounter(patientId, encounter.id, updated) : encounter;
  }

  // ─── Helpers ────────────────────────────────────────────────────────────────

  private knownAnswer(item: any, patient: Patient, encounter: Encounter, contactDate: Date, lastMenstrualPeriod: string | null): any | null {
    const definition: string = item.definition || '';
    const code: string | undefined = item.code?.[0]?.code;

    if (definition.endsWith('#Encounter.period.start')) {
      return { valueDateTime: encounter.period.start };
    }
    if (definition.endsWith('#Encounter.contactNumber')) {
      return { valueInteger: this.getContactNumber(encounter) };
    }
    if (definition.endsWith('#Patient.name.given') && patient.name?.[0]?.given?.[0]) {
      return { valueString: patient.name[0].given[0] };
    }
    if (definition.endsWith('#Patient.name.family') && patient.name?.[0]?.family) {
      return { valueString: patient.name[0].family };
    }
    if (definition.endsWith('#Patient.birthDate') && patient.birthDate) {
      return { valueDateTime: patient.birthDate };
    }
    if (code === ANC_LMP_CODE && lastMenstrualPeriod) {
      return { valueDate: lastMenstrualPeriod };
    }
    if (code === ANC_EDD_CODE && lastMenstrualPeriod) {
      return { valueDate: this.estimatedDateOfDelivery(lastMenstrualPeriod) };
    }
    if (code === ANC_GESTATIONAL_AGE_CODE) {
      const weeks = this.gestationalAgeWeeks(lastMenstrualPeriod, contactDate);
      if (weeks !== null) {
        return { valueQuantity: { value: weeks, unit: 'wk', system: 'http://unitsofmeasure.org', code: 'wk' } };
      }
    }
    return null;
  }

  private isAntenatalCase(episode: EpisodeOfCare): boolean {
    return !!episode.type?.some((type) =>
      type.coding?.some((coding) => coding.system === ANC_CARE_CODES && coding.code === ANC_CASE_CODE)
    );
  }

  private contactNumberExtensions(contactNumber: number): NonNullable<Encounter['extension']> {
    return CONTACT_NUMBER_EXTENSION_URLS.map((url) => ({ url, valueInteger: contactNumber }));
  }

  private patientDisplay(patient: Patient): string {
    const name = patient.name?.[0];
    return name?.text || [name?.given?.[0], name?.family].filter(Boolean).join(' ');
  }

  private newId(prefix: string): string {
    return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 11)}`;
  }

  private startOfDay(date: Date): Date {
    return new Date(date.getFullYear(), date.getMonth(), date.getDate());
  }

  private parseDateOnly(value: string): Date {
    const [year, month, day] = value.slice(0, 10).split('-').map(Number);
    return new Date(year, month - 1, day);
  }

  private toDateOnly(date: Date): string {
    const pad = (value: number) => String(value).padStart(2, '0');
    return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
  }
}
